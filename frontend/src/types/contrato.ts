/** true si A y B son asignables en ambos sentidos: campos de más o de menos, opcionales y tipos distintos */
type Igual<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false

type Coincide<A, B> =
  Igual<A, B> extends true ? true : { error: 'El tipo no coincide con el backend'; frontend: A; backend: B }

